import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { classifyTerminal, recordAttempt, chargedRunLines } from './attempt-terminal.mjs';
import { readMetricRows } from './efficiency-regression.mjs';
assert.equal(classifyTerminal({status:124, reason:'quota exhausted'}, 'exit-code'), 'local-timeout');
assert.equal(classifyTerminal({stage:'review-verdict', reason:'NOT_READY'}, 'success'), 'review-not-ready');
assert.equal(classifyTerminal({reason:'direct-main delivery failed', evidence:'GnuTLS recv error (-110)'}, 'success'), 'network-egress');
assert.equal(classifyTerminal({reason:'direct-main delivery failed', evidence:'Applied patch with conflicts'}, 'success'), 'rebase-conflict');
assert.equal(classifyTerminal({stage:'package-gate', reason:'pnpm test failed'}, 'success'), 'test-build-gate');
assert.equal(classifyTerminal(null, 'oom-kill'), 'host-memory');
assert.equal(classifyTerminal({status:143}, 'exit-code'), 'interrupted');
assert.equal(classifyTerminal({stage:'no-reviewable-diff', evidence:'**SCOPE-STOP:** fix belongs in independent PR #2758.'}, 'exit-code'), 'brief-ambiguous');
assert.equal(classifyTerminal({stage:'no-reviewable-diff', evidence:'缺实际容器 ID、宿主、近期日志。BLOCKED-CHECKS: ssh cihost'}, 'exit-code'), 'brief-ambiguous');
assert.equal(classifyTerminal({stage:'no-reviewable-diff', evidence:'本轮无需改代码。修复已存在于 origin/main。'}, 'exit-code'), 'no-change-needed');
assert.equal(classifyTerminal({stage:'no-reviewable-diff', evidence:'无需重复改代码。还需补齐 issue-linked 结案评论。'}, 'exit-code'), 'brief-ambiguous');
assert.equal(classifyTerminal({reason:'Codex provider outage (transport); retry the current rung', attempt_refunded:true}, 'success'), 'network-egress');
assert.equal(classifyTerminal({stage:'no-reviewable-diff', evidence:'BLOCKED-ON: #123 missing evidence from contract.'}, 'exit-code'), 'blocked-dependency');
const home = mkdtempSync(path.join(os.tmpdir(), 'attempt-terminal-'));
try {
  mkdirSync(path.join(home,'state'));
  const env = {INVOCATION_ID:'fixture-unit', SERVICE_RESULT:'success'};
  recordAttempt(home, 42, 'started', env, new Date('2026-10-12T00:00:00Z'));
  writeFileSync(path.join(home,'state/42.json'), JSON.stringify({implement_failure:{stage:'review-verdict', reason:'NOT_READY', recorded_at:'2026-10-12T00:00:05Z'}}));
  const result = recordAttempt(home, 42, 'terminal', env, new Date('2026-10-12T00:00:10Z'));
  assert.equal(result.terminal_cause,'review-not-ready');
  assert.equal(result.agent_seconds,10);
  recordAttempt(home, 42, 'terminal', env, new Date('2026-10-12T00:00:11Z'));
  assert.equal(readMetricRows(home).length,2);
  const next = {...env, INVOCATION_ID:'next-unit'};
  recordAttempt(home,42,'started',next,new Date('2026-10-12T01:00:00Z'));
  assert.equal(recordAttempt(home,42,'terminal',next,new Date('2026-10-12T01:00:01Z')).terminal_cause,'unknown');
  const transport = {...env, INVOCATION_ID:'transport-unit'};
  recordAttempt(home,42,'started',transport,new Date('2026-10-12T02:00:00Z'));
  writeFileSync(path.join(home,'state/42.json'), JSON.stringify({model_policy:{retry_note:{reason:'Codex provider outage (transport); retry the current rung',attempt_refunded:true,recorded_at:'2026-10-12T02:00:05Z'}}}));
  const deferred = recordAttempt(home,42,'terminal',transport,new Date('2026-10-12T02:00:10Z'));
  assert.equal(deferred.terminal_cause,'network-egress');
  assert.equal(deferred.attempt_refunded,true);
  const stopped = {...env, INVOCATION_ID:'stopped-unit', SERVICE_RESULT:'exit-code', EXIT_STATUS:'143'};
  recordAttempt(home,42,'started',stopped,new Date('2026-10-12T02:10:00Z'));
  writeFileSync(path.join(home,'state/42.json'), JSON.stringify({model_policy:{retry_note:{status:143,attempt_refunded:true,recorded_at:'2026-10-12T02:10:05Z'}}}));
  const interrupted = recordAttempt(home,42,'terminal',stopped,new Date('2026-10-12T02:10:10Z'));
  assert.equal(interrupted.terminal_cause,'interrupted');
  assert.equal(interrupted.attempt_refunded,true);
  assert.deepEqual(chargedRunLines(home,42,['1 implement-42-20261012T021001Z.log','2 implement-42-20261012T011001Z.log','3 implement-42-20261012T020001Z.log'],'current'), ['2 implement-42-20261012T011001Z.log']);
  const orphan = {...env, INVOCATION_ID:'pre-reboot'};
  recordAttempt(home,42,'started',orphan,new Date('2026-10-12T02:20:00Z'));
  recordAttempt(home,42,'started',{...env, INVOCATION_ID:'post-reboot'},new Date('2026-10-12T02:30:00Z'));
  assert.deepEqual(chargedRunLines(home,42,['1 implement-42-20261012T022001Z.log','2 implement-42-20261012T023001Z.log'],'new-boot'), []);
  // Only the pre-reboot invocation is orphaned on an old boot.
  const rows = readMetricRows(home);
  const boot = rows.find((row) => row.attempt_id === 'post-reboot').boot_id;
  rows.find((row) => row.attempt_id === 'pre-reboot').boot_id = 'old-boot';
  writeFileSync(path.join(home,'metrics', 'efficiency-2026-10.jsonl'), rows.map((row) => JSON.stringify(row)).join('\n')+'\n');
  assert.deepEqual(chargedRunLines(home,42,['1 implement-42-20261012T022001Z.log','2 implement-42-20261012T023001Z.log'],boot), ['2 implement-42-20261012T023001Z.log']);
  const decision = {...env, INVOCATION_ID:'decision-unit'};
  recordAttempt(home,42,'started',decision,new Date('2026-10-12T03:00:00Z'));
  writeFileSync(path.join(home,'state/42.json'), JSON.stringify({implement_decision:{question:'**SCOPE-STOP:** outside this brief.',requested_at:'2026-10-12T03:00:05Z'}}));
  assert.equal(recordAttempt(home,42,'terminal',decision,new Date('2026-10-12T03:00:10Z')).terminal_cause,'brief-ambiguous');
  const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const hook = spawnSync('bash', [path.join(repo,'engine/record-unit-result.sh'),'implement','42'], {
    env:{...process.env, AGENT_HOME:home, ZF_REPO_DIR:repo, INVOCATION_ID:'hook-unit', SERVICE_RESULT:'oom-kill', EXIT_CODE:'killed', EXIT_STATUS:'9'}, encoding:'utf8', timeout:10000,
  });
  assert.equal(hook.status,0,hook.stderr);
  assert.equal(readMetricRows(home).find((row)=>row.attempt_id==='hook-unit').terminal_cause,'host-memory');
  console.log('ok - same stream records one terminal per invocation, elapsed time, and no stale cause');
} finally {rmSync(home,{recursive:true,force:true});}
